"""Step 5 report: REPORT_V11.md (V9 / V10 / V11, measured numbers only) + outbox/v11_results.zip."""
import zipfile

from common import read_json
from paths11 import OUTBOX, WORK

NAMES = ('v9', 'v10', 'v11')


def get(path):
    return read_json(path) if path.exists() else None


def pct(x):
    return '-' if x is None else f'{100 * x:.2f}%'


def main():
    sel = get(WORK / 'select_v11' / 'selection.json')
    build = get(WORK / 'manifests_v11' / 'build_summary.json')
    labelfix = get(WORK / 'labelfix_v11' / 'summary.json')
    bench = {n: get(WORK / 'bench' / n / 'bench.json') for n in NAMES}
    temporal = {n: get(WORK / 'temporal' / n / 'temporal.json') for n in NAMES}
    history = get(WORK / 'train_v11' / 'history.json') or []
    L = ['# V11 results (generated by report_v11.py; all numbers measured on the lab PC)', '',
         'V11 = YOLOv9-S-TI-Lite 640 (same architecture as V9/V10), trained from COCO weights for 40 epochs on the V10 '
         'training set + label fixes, with zoom-out, small-flame paste and camera-degradation augmentation. '
         'Evaluation sets are byte-identical to V10. FASDD test not used.', '']
    if sel:
        b, v = sel['best'], sel['v10_reference']
        L += ['## Selection (rule fixed before training)', '', f'**{sel["reason"]}**', '',
              f'Best V11 checkpoint: epoch {b["epoch"]} (eligible: {sel["best_is_eligible"]}).', '',
              '| model | AP50 | AP50:95 | P@.40 | R@.40 | small-flame R (564 slice) | real-nuisance score |', '|---|---|---|---|---|---|---|',
              f'| V10 (frozen) | {pct(v["AP50"])} | {pct(v["AP50_95"])} | {pct(v["precision"])} | {pct(v["recall"])} | '
              f'{pct(v["small_recall"])} | {v["nuisance"]["score"]:.4f} |']
        for r in sel['candidates']:
            L.append(f'| V11 ep {r["epoch"]}{" *" if r["eligible"] else ""} | {pct(r["AP50"])} | {pct(r["AP50_95"])} | '
                     f'{pct(r["precision"])} | {pct(r["recall"])} | {pct(r["small_recall"])} | {r["nuisance"]["score"]:.4f} |')
        L += ['', '\\* = eligible under the floors ' + str({k: round(x, 4) for k, x in sel['floors'].items()}), '']
    if build or labelfix:
        L += ['## Data changes', '', f'Label fix: `{labelfix}`', '', f'Build: `{build}`', '']
    have = [n for n in NAMES if bench[n]]
    if have:
        L += ['## Detector benchmarks (same bench.py, same sets)', '', '| metric | ' + ' | '.join(have) + ' |',
              '|---|' + '---|' * len(have)]
        e1 = {n: bench[n].get('E1_fasdd_val') for n in have}
        for key in ('AP50', 'AP50_95', 'AP_small'):
            L.append(f'| val {key} | ' + ' | '.join(pct(e1[n]['coco'][key]) if e1[n] else '-' for n in have) + ' |')
        for key in ('precision', 'recall'):
            L.append(f'| val {key} @.40 | ' + ' | '.join(pct(e1[n]['at_040'][key]) if e1[n] else '-' for n in have) + ' |')
        L.append('| hn_val FP image rate @.40 | ' + ' | '.join(pct(bench[n]['E2_hn_val']['total']['fp_rate_040']) for n in have) + ' |')
        for cat in bench[have[0]]['E2_hn_val']['by_category']:
            L.append(f'| hn_val {cat} @.40 | ' + ' | '.join(
                pct(bench[n]['E2_hn_val']['by_category'].get(cat, {}).get('fp_rate_040')) for n in have) + ' |')
        L += ['', '## Own held-out clips (share of sampled frames with a box >= .40)', '',
              '| clip | kind | ' + ' | '.join(have) + ' |', '|---|---|' + '---|' * len(have)]
        for name, v in bench[have[0]].get('videos_frame_level', {}).items():
            if v['split'] != 'eval':
                continue
            key = 'fire_frame_hit_rate' if v['fire_frame_hit_rate'] is not None else 'nonfire_frame_fp_rate'
            kind = 'flame (higher better)' if key == 'fire_frame_hit_rate' else f'{v["category"]} (lower better)'
            L.append(f'| {name} | {kind} | ' + ' | '.join(
                pct(bench[n]['videos_frame_level'].get(name, {}).get(key)) for n in have) + ' |')
        L.append('')
    if any(temporal.values()):
        L += ['## Alarm events (temporal layer, held-out videos)', '',
              '| set | model | policy | event recall | median time to alarm (s) | false alarms / hour |', '|---|---|---|---|---|---|']
        sets = sorted({k for t in temporal.values() if t for k in t if k.endswith('_eval')})
        for s in sets:
            for n in NAMES:
                for policy, x in ((temporal[n] or {}).get(s) or {}).items():
                    L.append(f'| {s} | {n} | {policy} | {pct(x["event_recall"])} | {x["median_time_to_alarm_s"]} | '
                             f'{x["false_alarms_per_hour"]:.2f} |')
        L.append('')
    autopsy = WORK / 'select_v11' / 'AUTOPSY.md'
    if autopsy.exists():
        L += [autopsy.read_text(), '']
    if history:
        L += ['## Training curve (monitor val + hn_val per epoch)', '', '| epoch | mosaic | R@.40 | AP50 | hn_val FP image rate @.40 |', '|---|---|---|---|---|']
        for h in history:
            m = h['monitor_validation']
            L.append(f'| {h["epoch"]} | {h["mosaic"]} | {pct(m["at_confidence_0.40"]["recall"])} | {pct(m["coco"]["AP50"])} | '
                     f'{pct(h["hn_val"]["0.40"]["fp_image_rate"])} |')
        L.append('')
    L += ['Caveats: label fixes and spot check are CLIP + Claude visual review, not human. One training run: gains cannot '
          'be attributed to a single technique. Own clips are few and phone-recorded.']
    report = WORK / 'REPORT_V11.md'
    report.write_text('\n'.join(L))
    OUTBOX.mkdir(parents=True, exist_ok=True)
    archive = OUTBOX / 'v11_results.zip'
    with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as z:
        z.write(report, 'REPORT_V11.md')
        for folder in ('select_v11', 'bench/v11', 'temporal/v11', 'diagnose/v11', 'labelfix_v11', 'pilot_v11'):
            root = WORK / folder
            for path in sorted(root.rglob('*')) if root.exists() else []:
                big = path.suffix == '.pth' or path.stat().st_size > 50e6
                if path.is_file() and not big and 'cache' not in path.parts:
                    z.write(path, path.relative_to(WORK))
        for path in (WORK / 'train_v11' / 'history.json', WORK / 'manifests_v11' / 'build_summary.json',
                     WORK / 'manifests_v11' / 'augment_preview.json', WORK / 'select_v11' / 'v11_best.pth'):
            if path.exists():
                z.write(path, path.relative_to(WORK))
    print(report.read_text())
    print(f'\nSTOP: send {archive} to the owner.')


if __name__ == '__main__':
    main()
