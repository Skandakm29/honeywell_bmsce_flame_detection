"""REPORT_V12.md + outbox/v12_results.zip from whatever stages exist (measured numbers only)."""
import zipfile

from common import read_json
from common12 import OUTBOX, WORK, pct


def get(path):
    return read_json(path) if path.exists() else None


def sel_table(sel):
    v = sel['v10_reference']
    L = ['| model | AP50 | AP50:95 | P@.40 | R@.40 | small-flame R | nuisance |', '|---|---|---|---|---|---|---|',
         f'| V10 (frozen) | {pct(v["AP50"])} | {pct(v["AP50_95"])} | {pct(v["precision"])} | {pct(v["recall"])} | '
         f'{pct(v["small_recall"])} | {v["nuisance"]["score"]:.4f} |']
    for r in sel['candidates']:
        L.append(f'| {r["variant"]} ep {r["epoch"]}{" *" if r["eligible"] else ""} | {pct(r["AP50"])} | {pct(r["AP50_95"])} | '
                 f'{pct(r["precision"])} | {pct(r["recall"])} | {pct(r["small_recall"])} | {r["nuisance"]["score"]:.4f} |')
    L += ['', '\\* eligible; floors ' + str({k: round(x, 4) for k, x in sel['floors'].items()}), '']
    for key, label in (('operating_rule_v10', 'V10'), ('operating_rule', 'best checkpoint')):
        r = sel[key]
        c, b = r['chosen'], r['base']
        L.append(f'- Size-aware rule for {label}: ' + ('none helped within limits (keeps .40)' if r['side'] == 0 else
                 f'< {r["side"]} px from {r["threshold"]:.2f}: small R {pct(b["small_recall"])} -> {pct(c["small_recall"])}, '
                 f'R {pct(b["recall"])} -> {pct(c["recall"])}, P {pct(b["precision"])} -> {pct(c["precision"])}, '
                 f'nuisance {b["nuisance"]["score"]:.4f} -> {c["nuisance"]["score"]:.4f}'))
    return L + ['']


def flat(d, prefix=''):
    out = {}
    for k, v in (d or {}).items():
        if isinstance(v, dict) and len(prefix.split('.')) < 3:
            out.update(flat(v, f'{prefix}{k}.'))
        elif isinstance(v, (int, float)) and not isinstance(v, bool):
            out[prefix + k] = v
    return out


def main():
    L = ['# V12 results (generated by report12.py; measured on the lab PC)', '',
         'V12 = YOLOv9-S-TI-Lite 640 fine-tuned from frozen V10 (V10 settings, LR 3e-5, 8 epochs) in 3 variants on '
         'manifests_v11 data: a_data (V10 pipeline), b_zoom (mild zoom-out + camera degradations), c_zoom_paste '
         '(b + small-flame paste). Then optionally fine-tuned on owner recordings. Rules: PROTOCOL_V12.md.', '']
    if (WORK / 'opcheck_v12' / 'v10.md').exists():
        L += (WORK / 'opcheck_v12' / 'v10.md').read_text().splitlines() + ['']
    for name, title in (('select_v12', 'Step 3: fine-tune variants'), ('select_v12_rec', 'Step 4d: recordings fine-tune')):
        sel = get(WORK / name / 'selection.json')
        if sel:
            L += [f'## {title} (validation; rule fixed before training)', '', f'**{sel["reason"]}**', '',
                  f'Best: {sel["best"]["variant"]} epoch {sel["best"]["epoch"]} (eligible: {sel["best_is_eligible"]}).', '']
            L += sel_table(sel)
    rec = get(WORK / 'rec_v12' / 'finalize_summary.json')
    if rec:
        L += ['## Recordings used', '', '```', str(rec), '```', '']
    bench = {n: flat(get(WORK / 'bench' / n / 'bench.json')) for n in ('v10', 'v12', 'v12r')}
    temporal = {n: flat(get(WORK / 'temporal' / n / 'temporal.json')) for n in ('v10', 'v12', 'v12r')}
    for title, data in (('Benchmarks (bench.json, numeric fields)', bench), ('Temporal layer (temporal.json)', temporal)):
        names = [n for n in data if data[n]]
        if len(names) > 1:
            keys = sorted(set().union(*[data[n].keys() for n in names]))
            L += [f'## {title}', '', '| field | ' + ' | '.join(names) + ' |', '|---' * (len(names) + 1) + '|']
            for k in keys:
                if 'seconds' in k or k.endswith('images'):
                    continue
                L.append(f'| {k} | ' + ' | '.join(f'{data[n].get(k, "-"):.4g}' if isinstance(data[n].get(k), (int, float))
                                                  else '-' for n in names) + ' |')
            L.append('')
    test = get(WORK / 'test_v12' / 'test.json')
    if test:
        L += ['## Step 5: test (run once, after selection)', '', f'Final checkpoint: {test["final_checkpoint"]} ({test["selected"]}); '
              f'adopted over V10: {test["adopted"]} ({test["reason"]}).', '',
              '| FASDD test | P | R | FP boxes | small R |', '|---|---|---|---|---|']
        for key in ('fasdd_test_v10_rule', 'fasdd_test_v12_rule'):
            if key in test:
                for rule in ('at_040', 'chosen'):
                    r = test[key][rule]
                    L.append(f'| {key[11:14]} {rule} (<{r["side"]}px:{r["threshold"]}) | {pct(r["precision"])} | {pct(r["recall"])} | '
                             f'{r["FP"]} | {pct(r["small_recall"])} |')
        L.append('')
        if 'distance_test' in test:
            L += ['Distance test (corridor, never trained on). Flame clips: share of frames detected; '
                  'noflame: share of frames with a false alarm.', '',
                  '| clip | V10 .40 | V10 rule | V12 .40 | V12 rule |', '|---|---|---|---|---|']
            d10, d12 = test['distance_test']['v10'], test['distance_test']['v12']
            for clip in sorted(d12):
                L.append(f'| {clip} ({d12[clip]["frames"]} fr) | {pct(d10[clip]["rate_040"])} | {pct(d10[clip]["rate_rule"])} | '
                         f'{pct(d12[clip]["rate_040"])} | {pct(d12[clip]["rate_rule"])} |')
            L.append('')
    report = WORK / 'REPORT_V12.md'
    report.write_text('\n'.join(L) + '\n', encoding='utf-8')
    OUTBOX.mkdir(parents=True, exist_ok=True)
    files = [report] + [p for p in (WORK / 'opcheck_v12' / 'v10.json', WORK / 'select_v12' / 'selection.json',
                                    WORK / 'select_v12_rec' / 'selection.json', WORK / 'test_v12' / 'test.json',
                                    WORK / 'rec_v12' / 'finalize_summary.json', WORK / 'rec_v12' / 'propose_summary.json')
                        if p.exists()]
    files += [p for v in ('a_data', 'b_zoom', 'c_zoom_paste', 'rec') for p in [WORK / 'train_v12' / v / 'history.json'] if p.exists()]
    with zipfile.ZipFile(OUTBOX / 'v12_results.zip', 'w', zipfile.ZIP_DEFLATED) as z:
        for p in files:
            z.write(p, str(p.relative_to(WORK)))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
