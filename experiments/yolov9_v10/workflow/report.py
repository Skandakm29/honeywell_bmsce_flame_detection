"""Compile REPORT.md (V9 vs V10, detector and temporal layer) and outbox/step6_results.zip. Measured numbers only."""
import zipfile

from common import read_json, work_dir


def get(path):
    return read_json(path) if path.exists() else None


def pct(x):
    return '-' if x is None else f'{100 * x:.2f}%'


def main():
    work = work_dir()
    selection = get(work / 'select' / 'selection.json')
    bench = {n: get(work / 'bench' / n / 'bench.json') for n in ('v9', 'v10')}
    temporal = {n: get(work / 'temporal' / n / 'temporal.json') for n in ('v9', 'v10')}
    diagnose = {n: get(work / 'diagnose' / n / 'diagnose.json') for n in ('v9', 'v10')}
    lines = ['# V10 results (generated by report.py; all numbers measured on the lab PC)', '']
    if selection:
        s = selection['selected']
        f = selection['floors']
        lines += ['## Checkpoint selection (rule fixed before training)', '',
                  f'Selected: `{s["checkpoint"]}` (epoch {s["epoch"]}). {selection["reason"]}. '
                  f'Floors: AP50 >= {f["AP50"]:.4f}, recall@.40 >= {f["recall"]:.4f}, small-flame recall >= {f["small_recall"]:.4f}.',
                  *[f'WARNING: {w}' for w in selection.get('warnings', [])], '',
                  '| ckpt | AP50 | AP50:95 | P@.40 | R@.40 | small-flame R | real-nuisance score | scenes better / worse | synthetic screens flagged @.40 | eligible |',
                  '|---|---|---|---|---|---|---|---|---|---|']
        for r in selection['candidates']:
            sc = r['nuisance']['synthetic_screens']
            lines.append(f'| {r["checkpoint"]} | {pct(r["AP50"])} | {pct(r["AP50_95"])} | {pct(r["precision"])} | {pct(r["recall"])} | '
                         f'{pct(r["small_recall"])} ({r["small_tp"]}/{r["small_boxes"]}) | {r["nuisance"]["score"]:.4f} '
                         f'({r["nuisance"]["scenes"]} scenes) | {r["scenes_improved"]} / {r["scenes_worsened"]} | '
                         f'{pct(sc["flag_040"] / max(1, sc["images"]))} | {r["eligible"]} |')
        lines.append('')
    if all(bench.values()):
        lines += ['## Quick check: held-out own clips (share of frames with a detection >= .40)', '',
                  '| clip | kind | V9 | V10 |', '|---|---|---|---|']
        for name, v in bench['v9'].get('videos_frame_level', {}).items():
            if v['source'] != 'own' or v['split'] != 'eval':
                continue
            w = bench['v10']['videos_frame_level'].get(name, {})
            key = 'fire_frame_hit_rate' if v['fire_frame_hit_rate'] is not None else 'nonfire_frame_fp_rate'
            kind = 'flame (higher is better)' if key == 'fire_frame_hit_rate' else f'{v["category"]} (lower is better)'
            lines.append(f'| {name} | {kind} | {pct(v[key])} | {pct(w.get(key))} |')
        lines.append('')
    if all(bench.values()):
        lines += ['## Detector: V9 vs V10', '', '| metric | V9 | V10 |', '|---|---|---|']
        e1 = {n: b.get('E1_fasdd_val') for n, b in bench.items()}
        if all(e1.values()):
            for key in ('AP50', 'AP50_95', 'AP_small'):
                lines.append(f'| FASDD val {key} | {pct(e1["v9"]["coco"][key])} | {pct(e1["v10"]["coco"][key])} |')
            for key in ('precision', 'recall'):
                lines.append(f'| FASDD val {key} @.40 | {pct(e1["v9"]["at_040"][key])} | {pct(e1["v10"]["at_040"][key])} |')
            for seg in e1['v9']['segments']:
                k = 'recall' if seg.startswith('flame') else 'image_detection_rate_040'
                lines.append(f'| val {seg} {"recall" if k == "recall" else "FP image rate"} | '
                             f'{pct(e1["v9"]["segments"][seg][k])} | {pct(e1["v10"]["segments"][seg][k])} |')
        lines.append(f'| hn_val FP image rate @.40 (all) | {pct(bench["v9"]["E2_hn_val"]["total"]["fp_rate_040"])} | '
                     f'{pct(bench["v10"]["E2_hn_val"]["total"]["fp_rate_040"])} |')
        for cat, row in bench['v9']['E2_hn_val']['by_category'].items():
            other = bench['v10']['E2_hn_val']['by_category'].get(cat, {})
            lines.append(f'| hn_val {cat} (n={row["images"]}) FP @.40 | {pct(row["fp_rate_040"])} | {pct(other.get("fp_rate_040"))} |')
        if bench['v9'].get('E3_bowfire'):
            for key in ('fire_hit_rate_040', 'nonfire_fp_rate_040'):
                lines.append(f'| BoWFire {key} | {pct(bench["v9"]["E3_bowfire"][key])} | {pct(bench["v10"]["E3_bowfire"][key])} |')
        lines.append('')
    if all(temporal.values()):
        lines += ['## Alarm events on held-out videos (frame = raw detector; persist = fixed 60% of 2 s; persist_tuned = tuned on train clips; learned = verifier)', '',
                  '| set | model | policy | event recall | median time to alarm (s) | false alarms / hour |', '|---|---|---|---|---|---|']
        names = sorted({k for t in temporal.values() for k in t if k.endswith('_eval')})
        for name in names:
            for n in ('v9', 'v10'):
                for policy, s in (temporal[n].get(name) or {}).items():
                    lines.append(f'| {name} | {n} | {policy} | {pct(s["event_recall"])} | {s["median_time_to_alarm_s"]} | '
                                 f'{s["false_alarms_per_hour"]:.2f} ({s["false_alarms"]} in {s["hours"]:.2f} h) |')
        lines.append('')
    for n, d in diagnose.items():
        if d:
            lines += [f'## Diagnosis {n}', '', '| FP cluster | size | mean score |', '|---|---|---|']
            lines += [f'| {c["name"]} | {c["size"]} | {c["mean_score"]:.2f} |' for c in d.get('fp_clusters', [])]
            lines += ['', '| perturbation | FP mean conf change | FP drop below .40 | TP mean conf change | TP drop below .40 |', '|---|---|---|---|---|']
            for key in d['perturbation'].get('fp', {}):
                f, t = d['perturbation']['fp'][key], d['perturbation'].get('tp', {}).get(key, {})
                lines.append(f'| {key} | {f["mean_confidence_change"]:+.3f} | {pct(f["fraction_dropping_below_040"])} | '
                             f'{t.get("mean_confidence_change", 0):+.3f} | {pct(t.get("fraction_dropping_below_040"))} |')
            lines.append('')
    lines += ['Caveats: hn_val categories come from source labels and CLIP; mining reviews were CLIP + AI visual review, '
              'not human. Event metrics depend on the recorded clips. FASDD test is not used here.']
    report = work / 'REPORT.md'
    report.write_text('\n'.join(lines))
    archive = work / 'outbox' / 'step6_results.zip'
    archive.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as z:
        z.write(report, 'REPORT.md')
        for folder in ('select', 'bench', 'temporal', 'diagnose', 'manifests_v10', 'train_v10'):
            for path in sorted((work / folder).rglob('*')) if (work / folder).exists() else []:
                big = path.suffix == '.pth' or (path.suffix == '.json' and path.stat().st_size > 50e6)
                if path.is_file() and not big and 'cache' not in path.parts:
                    z.write(path, path.relative_to(work))
    print(report.read_text())
    print(f'\nSTOP 3: send {archive} (it includes the selected ONNX in select/export).')


if __name__ == '__main__':
    main()
